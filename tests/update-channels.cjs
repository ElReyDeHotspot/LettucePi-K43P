const fs=require('node:fs'),assert=require('node:assert/strict');
const root=__dirname+'/../payload/';
const source=fs.readFileSync(root+'www/luci-static/resources/view/chester-update/index.js','utf8');
const choose=new Function(source.slice(source.indexOf('function chooseRelease('),source.indexOf('function releaseNotes('))+'return chooseRelease;')();
const app={ok:true,manifest_checked:true,app_update:true,installed_bin:'64',latest_bin:'64',latest_app:1,update_available:false};
const full={ok:true,manifest_checked:true,installed_bin:'64',latest_bin:'65',update_available:true};
let result=choose(app,full);assert.equal(result.latest_bin,'65');assert.equal(result.app_update,false);assert.equal(result.update_available,true);
assert.equal(choose({...app,update_available:true},full).app_update,false,'Full firmware takes precedence');
assert.equal(choose(app,{...full,update_available:false}).app_update,true);
assert.equal(choose(app,{ok:false}).ok,false,'Do not report all software current when full channel failed');
assert.equal(choose({...app,update_available:true},{ok:false}).app_update,true,'Verified app still available');
const acl=JSON.parse(fs.readFileSync(root+'usr/share/rpcd/acl.d/luci-app-chester-update.json'))['luci-app-chester-update'];
assert.deepEqual(acl.read.file['/usr/sbin/chester-update firmware-status'],['exec']);
assert.deepEqual(acl.write.file['/usr/sbin/chester-update firmware-install *'],['exec']);
const progress=fs.readFileSync(root+'www/luci-static/resources/chester-ui/update-progress.js','utf8');
assert(progress.includes("this.model.firmware===true?'firmware-install':'install'"));
assert(progress.includes('firmware:m.firmware===true'),'Reload retains explicit firmware command');
assert(source.includes('firmware:this.info.app_update===false'));
const backend=fs.readFileSync(root+'usr/sbin/chester-update','utf8');
assert(backend.includes('VERSION_FILE=/rom/etc/chester-version'),'Firmware compares ROM counter, independent of overlay app build');
console.log('PASS update channels: BIN65 full release, app fallback, offline handling, exact ACL, explicit install routing/resume and ROM counter.');
